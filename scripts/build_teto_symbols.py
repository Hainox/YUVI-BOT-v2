# матирование
# ─────────────────────────────────────────────────────────────────────────────
def _border_bg(rgb: np.ndarray) -> np.ndarray:
    """Цвет фона = медиана рамки кадра (а не «проверка на чистый белый»)."""
    ring = np.concatenate([
        rgb[:3].reshape(-1, 3), rgb[-3:].reshape(-1, 3),
        rgb[:, :3].reshape(-1, 3), rgb[:, -3:].reshape(-1, 3),
    ])
    return np.median(ring, axis=0)


def key_matte(rgb: np.ndarray, spec: SymbolSpec) -> tuple[np.ndarray, np.ndarray]:
    """Альфа заливкой ОТ ГРАНИЦЫ кадра + un-premultiply кромки.

    Возвращает (rgb_без_фонового_гало, alpha 0..1).
    """
    h, w, _ = rgb.shape
    bg = _border_bg(rgb)
    dist = np.abs(rgb - bg).max(axis=2)  # L∞ по каналам — хватает для плоского фона

    flood_tol = spec.flood_tol or spec.tol_hi
    lab, n = ndimage.label(dist <= flood_tol)
    border = np.concatenate([lab[0], lab[-1], lab[:, 0], lab[:, -1]])
    outside_ids = set(int(i) for i in np.unique(border) if i)
    outside = (
        np.isin(lab, list(outside_ids)) if outside_ids
        else np.zeros_like(lab, bool)
    )

    # Плавная кромка только внутри заведомо-фоновой области. Верх рампы —
    # ИМЕННО flood_tol, а не tol_hi: пиксель, который заливка опознала как
    # фон, не имеет права выйти непрозрачным (см. «баг рампы» в докстринге).
    ramp_hi = max(flood_tol, spec.tol_hi)
    ramp = np.clip((dist - spec.tol_lo) / max(ramp_hi - spec.tol_lo, 1e-6), 0, 1)
    alpha = np.where(outside, ramp, 1.0).astype(np.float32)

    # уровни альфы: поджим размытой фото-кромки
    lo, hi = spec.choke
    if (lo, hi) != (0.0, 1.0):
        alpha = np.clip((alpha - lo) / max(hi - lo, 1e-6), 0, 1)

    solid = alpha > 0.5
    if spec.seal:  # зашить открытый контур (скетч)
        r = spec.seal
        yy, xx = np.mgrid[-r:r + 1, -r:r + 1]
        disk = (xx ** 2 + yy ** 2) <= r * r
        # рамку кадра для закрытия ПРОДЛЕВАЕМ репликацией края: у скетча
        # витки дрель-причёски уходят за кадр, и без этого закрытие у самой
        # границы вело себя иначе, чем внутри — на срезе оставались
        # прямоугольные откусы между витками (ровно те же, что и в середине,
        # только незашитые)
        pad = ndimage.binary_closing(
            np.pad(solid, r, mode="edge"), structure=disk
        )
        solid = pad[r:-r, r:-r]
    solid = ndimage.binary_fill_holes(solid)  # страховка от дыр в субъекте

    # мусор от JPEG: выбросить крошечные изолированные компоненты
    # (+ опционально мелкие ОТДЕЛЬНЫЕ куски — см. min_frac у teto_drill_rage)
    min_area = max(24.0, 4e-5 * w * h, spec.min_area)
    lab2, n2 = ndimage.label(solid)
    if n2:
        areas = np.asarray(
            ndimage.sum(np.ones_like(lab2), lab2, index=range(1, n2 + 1))
        )
        if spec.min_frac:
            min_area = max(min_area, spec.min_frac * float(areas.max()))
        drop = [i + 1 for i, a in enumerate(areas) if a < min_area]
        if drop:
            solid[np.isin(lab2, drop)] = False

    alpha = np.maximum(alpha, solid.astype(np.float32))
    alpha[~solid & (alpha > 0.5)] = 0.0
    if spec.min_frac or spec.min_area:
        # у выброшенных кусков надо убить и полупрозрачную бахрому: иначе
        # призрачные контуры остаются, тянут alpha-bbox и дают дырки в альфе
        keep = ndimage.binary_dilation(solid, iterations=2)
        alpha *= keep.astype(np.float32)

    # un-premultiply: убрать плёнку фона с полупрозрачных пикселей
    out = rgb.astype(np.float32)
    band = (alpha > 0.02) & (alpha < 0.985)
    if band.any():
        a = alpha[band][:, None]
        fg = (out[band] - (1.0 - a) * bg[None, :]) / np.maximum(a, 0.02)
        out[band] = np.clip(fg, 0, 255)

    if spec.duotone:  # скетч → чернила/бумага
        ink, paper = (np.array(c, np.float32) for c in spec.duotone)
        lum = out.mean(axis=2, keepdims=True) / 255.0
        lum = np.clip((lum - 0.16) / 0.72, 0, 1) ** 0.92
        out = ink[None, None, :] + (paper - ink)[None, None, :] * lum

    return out, alpha


def _superellipse(w: int, h: int, feather: float, n: float = 4.0) -> np.ndarray:
    """Маска скруглённого квадрата (squircle) с растушёванным краем."""
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    ax, ay = (w - 1) / 2.0, (h - 1) / 2.0
    u = np.abs((xx - ax) / ax)
    v = np.abs((yy - ay) / ay)
    r = (u ** n + v ** n) ** (1.0 / n)  # 1.0 = граница фигуры
    # растушёвка шириной feather px вдоль минимальной полуоси
    band = feather / min(ax, ay)
    return np.clip((1.0 - r) / max(band, 1e-6), 0, 1).astype(np.float32)


def _focus_mask(
    w: int, h: int, cx: float, cy: float, rx: float, ry: float, n: float
) -> np.ndarray:
    """Мягкое центральное пятно в долях кадра — через него виден резкий субъект.

    Растушёвка здесь НАМЕРЕННО очень широкая (переход занимает половину
    радиуса): резкая граница между резким и размытым читается как «вырезали
    овал и вклеили», а нужен эффект глубины резкости.
    """
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    u = (xx - cx * w) / (rx * w)
    v = (yy - cy * h) / (ry * h)
    r = (np.abs(u) ** n + np.abs(v) ** n) ** (1.0 / n)
    return np.clip((1.35 - r) / 0.85, 0, 1).astype(np.float32)


def medallion_matte(rgb: np.ndarray, spec: SymbolSpec) -> tuple[np.ndarray, np.ndarray]:
    """Медальон: сохранённый фон читается как намеренная подложка."""
    h, w, _ = rgb.shape
    alpha = _superellipse(w, h, spec.feather)
    out = rgb.astype(np.float32)

    if spec.bg_blur and spec.focus:
        # один резкий субъект на мягкой пластине — то, что превращает
        # «обрезок фотографии» в портрет; размытие идёт ДО грейда и виньетки,
        # иначе размывались бы уже поднятые тени и виньетка ползла бы пятнами
        soft = ndimage.gaussian_filter(out, (spec.bg_blur, spec.bg_blur, 0))
        m = _focus_mask(w, h, *spec.focus)[..., None]
        out = soft + (out - soft) * m

    if spec.pink_lift:  # тёмный скаттер не должен утонуть в тёмном UI
        k = spec.pink_lift
        shade = 1.0 - (out.mean(axis=2, keepdims=True) / 255.0)
        tint = np.array(ACCENT_PINK, np.float32)[None, None, :]
        out = out * (1 - k * shade) + tint * (k * shade)

    if spec.vignette:  # затемнение к краю — «портрет», а не «обрезок фото»
        r = 1.0 - _superellipse(w, h, min(w, h) * 0.40)
        out *= (1.0 - spec.vignette * r[..., None])

    return np.clip(out, 0, 255), alpha


def arc_cut(alpha: np.ndarray, arc: tuple[float, float, float, float]) -> np.ndarray:
    """Скруглить сторону силуэта, срезанную рамкой исходника (die-cut).

    Зачем отдельный механизм, а не «подобрать кроп»: у трёх исходников
    субъект физически ОБРЕЗАН краем кадра — 3D-рендер рыцаря нарисован с
    прямым горизонтальным срезом по талии на y=452, у скетча дрель-косы
    уходят за левый и правый край, у собаки-химеры кроп по x=660 режет
    туловище. Любой кроп через такую фигуру даёт хорду, то есть прямой
    отрезок; кроп «повыше» через круглый щит даёт хорду ТОЙ ЖЕ длины или
    длиннее (щит шире всего у центра). Прямой отрезок с ровным по линейке
    рантом читается как оторванный стикер, поэтому срез скругляется явно:
    из края вырезается параболический полумесяц глубиной `depth` (в долях
    габарита субъекта), и рант замыкается дугой, как у настоящей вырубки.

    `arc` = (слева, справа, сверху, снизу), 0 → сторона не трогается.
    """
    if not any(arc):
        return alpha
    h, w = alpha.shape
    for side, depth in zip(("left", "right", "top", "bottom"), arc):
        if not depth:
            continue
        solid = alpha > 0.5
        ys, xs = np.nonzero(solid)
        if not len(ys):
            break
        vertical = side in ("left", "right")
        # экстремальная линия среза и протяжённость субъекта вдоль неё
        if vertical:
            e = int(xs.min() if side == "left" else xs.max())
            probe = solid[:, min(e + 2, w - 1) if side == "left" else max(e - 2, 0)]
            span = float(xs.max() - xs.min() + 1)
        else:
            e = int(ys.min() if side == "top" else ys.max())
            probe = solid[min(e + 2, h - 1) if side == "top" else max(e - 2, 0), :]
            span = float(ys.max() - ys.min() + 1)
        run = np.nonzero(probe)[0]
        if len(run) < 8:
            continue
        c = (float(run.min()) + float(run.max())) / 2.0
        half = max((float(run.max()) - float(run.min())) / 2.0, 1.0)
        amp = depth * span
        t = np.clip((np.arange(len(probe), dtype=np.float32) - c) / half, -1, 1)
        edge = e + amp * t ** 2 if side in ("left", "top") else e - amp * t ** 2
        grid = np.arange(w if vertical else h, dtype=np.float32)
        if side in ("left", "top"):
            keep = np.clip((grid[None, :] - edge[:, None]) / 3.0 + 1.0, 0, 1)
        else:
            keep = np.clip((edge[:, None] - grid[None, :]) / 3.0 + 1.0, 0, 1)
        alpha = alpha * (keep if vertical else keep.T)
    return alpha


# ─────────────────────────────────────────────────────────────────────────────
# нормализация кадра
# ─────────────────────────────────────────────────────────────────────────────
def normalize(
    rgb: np.ndarray, alpha: np.ndarray, spec: SymbolSpec
) -> tuple[Image.Image, float, float]:
    """Привести ПЛОЩАДЬ непрозрачного ядра к общей цели, центрировать.

    Возвращает (холст, эффективный масштаб к исходнику, доля площади ядра).
    """
    ys, xs = np.nonzero(alpha > 0.06)
    if not len(ys):
        raise RuntimeError("пустая альфа — матирование не нашло субъекта")
    t, b, l, r = ys.min(), ys.max() + 1, xs.min(), xs.max() + 1

    sub = np.dstack([rgb, alpha * 255.0]).astype(np.uint8)[t:b, l:r]
    im = Image.fromarray(sub, "RGBA")
    sw, sh = im.size

    core = float((alpha[t:b, l:r] > 0.5).sum())
    if core <= 0:
        raise RuntimeError("непрозрачное ядро пустое")

    # главная цель — площадь; габарит и апскейл только ограничивают сверху
    area_fit = spec.area_fit or AREA_FIT
    scale = (area_fit * WORK) / np.sqrt(core)
    scale = min(scale, (spec.max_long or MAX_LONG) * WORK / max(sw, sh))
    if scale / SS > MAX_UPSCALE:
        scale = MAX_UPSCALE * SS

    nw, nh = max(1, round(sw * scale)), max(1, round(sh * scale))
    im = im.resize((nw, nh), Image.LANCZOS)
    if spec.sharpen:
        im = im.filter(
            ImageFilter.UnsharpMask(
                radius=2.0, percent=int(60 * spec.sharpen), threshold=3
            )
        )

    canvas = Image.new("RGBA", (WORK, WORK), (0, 0, 0, 0))
    canvas.paste(im, ((WORK - nw) // 2, (WORK - nh) // 2))
    return canvas, scale / SS, core * scale * scale / (WORK * WORK)


# ─────────────────────────────────────────────────────────────────────────────
# общая обработка
# ─────────────────────────────────────────────────────────────────────────────
def _solid(color: tuple[int, int, int], mask: np.ndarray) -> Image.Image:
    layer = Image.new("RGBA", (WORK, WORK), color + (0,))
    layer.putalpha(Image.fromarray((np.clip(mask, 0, 1) * 255).astype(np.uint8), "L"))
    return layer


def _vgrad(
    top: tuple[int, int, int], bottom: tuple[int, int, int], mask: np.ndarray
) -> Image.Image:
    ramp = np.linspace(0, 1, WORK, dtype=np.float32)[:, None, None]
    a = np.array(top, np.float32)[None, None, :]
    b = np.array(bottom, np.float32)[None, None, :]
    rgb = (a + (b - a) * ramp).repeat(WORK, axis=1)
    layer = np.dstack([rgb, np.clip(mask, 0, 1) * 255.0]).astype(np.uint8)
    return Image.fromarray(layer, "RGBA")


def _blur(mask: np.ndarray, sigma: float) -> np.ndarray:
    if sigma <= 0:
        return mask
    return ndimage.gaussian_filter(mask.astype(np.float32), sigma)


def treat(subject: Image.Image, tier: Tier, spec: SymbolSpec) -> Image.Image:
    """Единая обводка-стикер + римлайт + свечение + грейдинг."""
    a = np.asarray(subject.getchannel("A"), np.float32) / 255.0

    # --- персональные правки ДО общего грейда -----------------------------
    body = subject
    if spec.shadow_lift or spec.local_contrast:
        arr = np.asarray(body.convert("RGB"), np.float32)
        if spec.shadow_lift:
            # подъём только тёмного: вес гаснет к яркости 96, поэтому
            # светлые части (платье, кожа, розовые волосы) не выцветают
            lum = arr.mean(axis=2, keepdims=True)
            arr = arr + spec.shadow_lift * np.clip(1.0 - lum / 96.0, 0, 1)
        rgb_im = Image.fromarray(np.clip(arr, 0, 255).astype(np.uint8), "RGB")
        if spec.local_contrast:
            # крупный радиус = локальный контраст, а не «резкость»: вытягивает
            # фактуру (заклёпки и обод щита), не трогая мелкий шум JPEG
            rgb_im = rgb_im.filter(
                ImageFilter.UnsharpMask(
                    radius=8.0 * SS, percent=int(100 * spec.local_contrast),
                    threshold=2,
                )
            )
        body = Image.merge("RGBA", (*rgb_im.split(), subject.getchannel("A")))

    # --- грейдинг субъекта -------------------------------------------------
    rgb = body.convert("RGB")
    rgb = ImageEnhance.Color(rgb).enhance(tier.saturation * spec.sat)
    rgb = ImageEnhance.Contrast(rgb).enhance(tier.contrast * spec.contrast)
    rgb = ImageEnhance.Brightness(rgb).enhance(tier.brightness * spec.brightness)
    body = Image.merge("RGBA", (*rgb.split(), subject.getchannel("A")))

    # --- единое направление света: верхний хайлайт + нижняя контактная тень -
    ramp = np.linspace(1.0, 0.0, WORK, dtype=np.float32)[:, None] ** 2.2
    body.alpha_composite(_solid((255, 255, 255), ramp * a * tier.toplight))
    ramp2 = np.linspace(0.0, 1.0, WORK, dtype=np.float32)[:, None] ** 3.0
    body.alpha_composite(_solid(INK, ramp2 * a * 0.22))

    if spec.rim_light:
        # светлая кромка ИЗНУТРИ по нижнему краю силуэта: тёмный низ
        # (лапы химеры, ботфорты нотки, обод щита) иначе слипается с
        # #0d0a18, а расширять внешний рант нельзя — он кодирует тир
        color, strength = spec.rim_light
        solid_a = (a > 0.5).astype(np.float32)
        k = int(5 * SS)
        band = np.clip(solid_a - np.roll(solid_a, -k, axis=0), 0, 1)
        band[-k:] = 0.0
        band = _blur(band, 2.0 * SS) * solid_a
        body.alpha_composite(_solid(color, band * strength))

    # --- огибающая силуэта: вырубка идёт по «телу», а не по каждой волосинке
    env = (_blur(a, 7.0 * SS) > 0.5)
    env |= a > 0.995
    env = ndimage.binary_fill_holes(env)
    dist = ndimage.distance_transform_edt(~env)  # px наружу от силуэта

    def ring(px: float) -> np.ndarray:
        return np.clip(px - dist + 0.5, 0, 1)

    key_m = ring(tier.keyline)
    rim_m = ring(tier.keyline + tier.rim)
    hair_m = None
    if tier.hairline:
        if tier.hairline_inner:
            # белое кольцо ВНУТРИ ранта (сразу за кейлайном), цвет тира
            # остаётся снаружи и определяет прочтение символа издалека
            hair_m = np.clip(ring(tier.keyline + tier.hairline_px) - key_m, 0, 1)
        else:
            outer = ring(tier.keyline + tier.rim + tier.hairline_px)
            hair_m = np.clip(outer - rim_m, 0, 1)

    # --- сборка ------------------------------------------------------------
    out = Image.new("RGBA", (WORK, WORK), (0, 0, 0, 0))

    if tier.halo_radius:  # широкий ореол
        halo = _blur(rim_m, tier.halo_radius)
        out.alpha_composite(_solid(tier.glow, halo * tier.halo_alpha))
    glow = _blur(rim_m, tier.glow_radius)
    out.alpha_composite(_solid(tier.glow, glow * tier.glow_alpha))

    shadow = np.roll(_blur(rim_m, 9.0 * SS), int(5 * SS), axis=0)
    out.alpha_composite(_solid((0x06, 0x04, 0x0D), shadow * tier.shadow_alpha))

    if hair_m is not None and not tier.hairline_inner:
        out.alpha_composite(_solid(tier.hairline, hair_m))
    if tier.rim_color_bottom:
        out.alpha_composite(_vgrad(tier.rim_color, tier.rim_color_bottom, rim_m))
    else:
        out.alpha_composite(_solid(tier.rim_color, rim_m))
    if hair_m is not None and tier.hairline_inner:
        out.alpha_composite(_solid(tier.hairline, hair_m))
    out.alpha_composite(_solid(INK, key_m))
    out.alpha_composite(body)

    return out


def finish(im: Image.Image) -> Image.Image:
    small = im.resize((OUT_SIZE, OUT_SIZE), Image.LANCZOS)
    rgb = small.convert("RGB").filter(
        ImageFilter.UnsharpMask(radius=1.2, percent=42, threshold=3)
    )
    return Image.merge("RGBA", (*rgb.split(), small.getchannel("A")))


# ─────────────────────────────────────────────────────────────────────────────
def _scrub(rgb: np.ndarray, box: tuple[int, int, int, int]) -> None:
    """Заровнять бокс построчной интерполяцией соседних столбцов (in-place).

    Ради этого приёма и существует поле `scrub`: заливка одним цветом на
    градиенте бумаги оставляет видимую ступеньку, а лерп между левым и
    правым краем бокса повторяет и градиент, и его наклон. Столбцы-доноры
    предварительно сглаживаются вдоль Y, иначе JPEG-шум донора тянется
    через весь бокс горизонтальными полосами.
    """
    l, t, r, b = box
    h_src = rgb.shape[0]
    t, b = max(0, t), min(h_src, b)
    left = rgb[t:b, max(l - 4, 0):l].mean(axis=1)
    right = rgb[t:b, r:r + 4].mean(axis=1)
    left = ndimage.gaussian_filter1d(left, 3.0, axis=0)
    right = ndimage.gaussian_filter1d(right, 3.0, axis=0)
    w = np.linspace(0.0, 1.0, r - l, dtype=np.float32)[None, :, None]
    rgb[t:b, l:r] = left[:, None, :] * (1 - w) + right[:, None, :] * w


def build(symbol_id: str, spec: SymbolSpec) -> str:
    path = SRC_DIR / spec.file
    if not path.exists():
        sys.exit(
            f"нет исходника {path}\n"
            f"Ожидается каталог {SRC_DIR} с 10 JPEG "
            f"(имя = <symbol_id>--IMG_xxxx.jpg)."
        )
    src = Image.open(path).convert("RGB")
    full = np.asarray(src, np.float32).copy()
    for box in spec.scrub:  # логотип на короне → ДО кропа, в координатах файла
        _scrub(full, box)
    rgb = full
    if spec.crop:
        l, t, r, b = spec.crop
        rgb = rgb[t:b, l:r].copy()

    bg = _border_bg(rgb)
    for l, t, r, b in spec.wipe:  # вотермарка/глифы → фоном ДО кейинга
        rgb[t:b, l:r] = bg
    for poly in spec.wipe_poly:
        m = Image.new("L", (rgb.shape[1], rgb.shape[0]), 0)
        ImageDraw.Draw(m).polygon(poly, fill=255)
        rgb[np.asarray(m) > 0] = bg
    for l, t, r, b, sat_max, dist_max in spec.desat_wipe:
        box = rgb[t:b, l:r]
        sat = box.max(axis=2) - box.min(axis=2)
        dist = np.abs(box - bg).max(axis=2)
        box[(sat < sat_max) & (dist < dist_max)] = bg
    if spec.pad:  # холст с запасом фона: заливка от границы обойдёт субъект
        rgb = np.pad(
            rgb, ((spec.pad, spec.pad), (spec.pad, spec.pad), (0, 0)),
            mode="constant",
        )
        rgb[:spec.pad], rgb[-spec.pad:] = bg, bg
        rgb[:, :spec.pad], rgb[:, -spec.pad:] = bg, bg

    if spec.mode == "key":
        rgb, alpha = key_matte(rgb, spec)
    elif spec.mode == "medallion":
        rgb, alpha = medallion_matte(rgb, spec)
    else:  # pragma: no cover
        raise ValueError(spec.mode)

    alpha = arc_cut(alpha, spec.arc)
    canvas, native, core_share = normalize(rgb, alpha, spec)
    out = finish(treat(canvas, TIERS[spec.tier], spec))

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    dst = OUT_DIR / f"{symbol_id}.webp"
    try:
        out.save(dst, "WEBP", quality=88, alpha_quality=92, method=6, exact=False)
    except TypeError:  # старая Pillow без alpha_quality
        out.save(dst, "WEBP", quality=88, method=6)

    # самопроверка перечитыванием файла: дыры внутри субъекта = прозрачные
    # области, НЕ связанные с рамкой холста (мелочь <60 px — дизеринг WebP)
    kb = dst.stat().st_size / 1024
    a = np.asarray(Image.open(dst).convert("RGBA").getchannel("A"))
    lab, n = ndimage.label(a < 10)
    outer = set(int(i) for i in np.unique(
        np.concatenate([lab[0], lab[-1], lab[:, 0], lab[:, -1]])
    )) - {0}
    holes = sum(
        1 for i in range(1, n + 1)
        if i not in outer and int((lab == i).sum()) > 60
    )
    # альфа на четырёх границах файла: у вайлда/скаттера широкий ореол
    # упирался в край и давал видимое квадратное поле — держим ≤4
    edge = max(a[0].max(), a[-1].max(), a[:, 0].max(), a[:, -1].max())
    ys, xs = np.nonzero(a > 200)
    long_side = max(xs.max() - xs.min(), ys.max() - ys.min()) + 1
    return (
        f"{symbol_id:22s} {spec.tier:13s} {spec.mode:9s} "
        f"{kb:6.1f} KB  scale={native:.2f}x  тело={100 * long_side / OUT_SIZE:4.1f}%  "
        f"субъект={100 * core_share:4.1f}%  ядро={100 * (a > 128).mean():4.1f}%  "
        f"край={edge:3d}  дыр={holes}"
    )


def main() -> None:
    if not SRC_DIR.is_dir():
        sys.exit(f"нет каталога исходников {SRC_DIR}")
    print(f"→ {OUT_DIR}")
    for symbol_id, spec in SYMBOLS.items():
        print("  " + build(symbol_id, spec))


if __name__ == "__main__":
    main()
